import { test, expect, login, logout, control, rest, seedCart } from './helpers'
import type { Cart, Session } from '../../src/domain/types'

test('registration validates fields, rejects existing accounts and creates a persistent session', async ({ page }) => {
  await page.goto('/register?redirect=%2Faccount')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.locator('#auth-email')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#auth-email-error')).toHaveText('Informe um e-mail válido.')
  await page.locator('#auth-username').fill('colecionador')
  await page.locator('#auth-email').fill('colecionador@kurio.test')
  await page.locator('#auth-password').fill('Kurio123!')
  await page.locator('#auth-confirm').fill('Different123!')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.locator('#auth-confirm-error')).toHaveText('As senhas não coincidem.')
  await page.locator('#auth-confirm').fill('Kurio123!')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page.locator('#auth-email-error')).toHaveText('E-mail ou usuário já cadastrado.')
  await page.locator('#auth-username').fill('e2e.collector')
  await page.locator('#auth-email').fill('e2e@kurio.test')
  await page.getByRole('button', { name: 'Criar perfil', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.locator('#profile-email')).toHaveValue('e2e@kurio.test')
  await page.reload()
  await expect(page.locator('#profile-email')).toHaveValue('e2e@kurio.test')
  await logout(page)
  await page.goto('/account/wallets')
  await expect(page).toHaveURL(/\/login\?redirect=/)
})

test('invalid login shows an associated field error and expired sessions return to login', async ({ page }) => {
  await page.goto('/login?redirect=%2Faccount')
  await page.locator('#auth-email').fill('colecionador@kurio.test')
  await page.locator('#auth-password').fill('Incorrect123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.locator('#auth-email-error')).toHaveText('Confira suas credenciais.')
  await page.locator('#auth-password').fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await control(page, { action: 'expire' })
  await page.goto('/account/wallets')
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await expect(page.locator('#auth-email')).toBeVisible()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('kurio.session'))).toBeNull()
})

test('logout and user switching isolate carts, favorites, profile, wallets and receipts', async ({ page }) => {
  await login(page)
  await seedCart(page, 2)
  await page.goto('/')
  const savedFavorite = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/favorites/emerald-ape-042')
  await page.getByRole('button', { name: 'Favoritar Emerald Ape #042', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
  const favoriteResponse = await savedFavorite
  expect(favoriteResponse.status()).toBe(200)
  await favoriteResponse.finished()
  await logout(page)
  await login(page, 'nova@kurio.test')
  await expect(page.locator('#profile-email')).toHaveValue('nova@kurio.test')
  expect((await rest<Cart>(page, '/cart')).items).toEqual([])
  expect(await rest<string[]>(page, '/favorites')).toEqual([])
  await page.goto('/account/wallets')
  await expect(page.getByText('nova.eth', { exact: true })).toBeVisible()
  await expect(page.getByText('colecionador.eth', { exact: true })).toHaveCount(0)
  await page.goto('/favorites')
  await expect(page.getByText(/Você ainda não adicionou NFTs/)).toBeVisible()
  await logout(page)
  await login(page)
  await page.goto('/cart')
  await expect(page.getByRole('status', { name: 'Quantidade' })).toHaveText('2')
  await page.goto('/favorites')
  await expect(page.getByRole('link', { name: 'Emerald Ape #042', exact: true })).toBeVisible()
  const session = await rest<Session>(page, '/session')
  expect(session.user?.id).toBe('user-collector')
})

test('favorite optimistic state rolls back a failed mutation and survives successful refresh', async ({ page }) => {
  await login(page, undefined, undefined, '/')
  await control(page, { action: 'scenario', scenario: 'favorite-error' })
  const favorite = page.getByRole('button', { name: 'Favoritar Emerald Ape #042', exact: true })
  await favorite.click()
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('alert').filter({ hasText: 'Não foi possível salvar seu favorito' })).toBeVisible()
  await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  expect(await rest<string[]>(page, '/favorites')).toEqual([])
  await control(page, { action: 'scenario', scenario: 'success' })
  await favorite.click()
  await expect.poll(() => rest<string[]>(page, '/favorites')).toEqual(['emerald-ape-042'])
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos' })).toHaveAttribute('aria-pressed', 'true')
})

test('guest cart quantities, removal and coupons persist through login and refresh', async ({ page }) => {
  await seedCart(page, 2)
  await seedCart(page, 1, 'sage-nomad-009')
  await page.goto('/cart')
  const emerald = page.locator('.cart-row').filter({ hasText: 'Emerald Ape #042' })
  await page.getByRole('button', { name: 'Aumentar quantidade de Emerald Ape #042', exact: true }).click()
  await expect(emerald.getByRole('status', { name: 'Quantidade' })).toHaveText('3')
  await page.getByRole('button', { name: 'Diminuir quantidade de Emerald Ape #042', exact: true }).click()
  await expect(emerald.getByRole('status', { name: 'Quantidade' })).toHaveText('2')
  await page.getByRole('button', { name: 'Remover Sage Nomad #009', exact: true }).click()
  await expect(page.locator('.cart-row')).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Código promocional' }).fill('WRONG')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.locator('#coupon-error')).toHaveText('Confira o código do cupom.')
  await page.getByRole('textbox', { name: 'Código promocional' }).fill('EXPIRED')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.locator('#coupon-error')).toHaveText('Cupom expirado.')
  await page.getByRole('textbox', { name: 'Código promocional' }).fill('KURIO10')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('button', { name: 'KURIO10 · Remover código' })).toBeVisible()
  await expect(page.locator('.purchase-total dd')).toHaveText('2.158 ETH')
  await page.reload()
  await expect(page.locator('.cart-row').getByRole('status', { name: 'Quantidade' })).toHaveText('2')
  await page.getByRole('link', { name: 'Conectar e finalizar', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.locator('#auth-email').fill('colecionador@kurio.test')
  await page.locator('#auth-password').fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout$/)
  expect((await rest<Cart>(page, '/cart')).items.map(item => item.quantity)).toEqual([2])
  expect((await rest<Cart>(page, '/cart')).coupon).toBe('KURIO10')
  await page.reload()
  await expect(page.locator('.purchase-total dd')).toHaveText('2.158 ETH')
  await page.goto('/cart')
  await page.getByRole('button', { name: 'KURIO10 · Remover código' }).click()
  await expect(page.locator('.purchase-total dd')).toHaveText('2.396 ETH')
})
