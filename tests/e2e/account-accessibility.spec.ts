import { test, expect, login, logout, rest, seedCart } from './helpers'
import type { User, Wallet } from '../../src/domain/types'

test('profile, avatar and password validate and persist through refresh and reauthentication', async ({ page }) => {
  await login(page)
  await page.locator('#profile-displayName').fill('')
  await page.locator('#profile-email').fill('invalid')
  await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
  await expect(page.locator('#profile-displayName')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('#profile-email-error')).toHaveText('Informe um e-mail válido.')
  await page.locator('#profile-displayName').fill('Colecionador E2E')
  await page.locator('#profile-email').fill('colecionador@kurio.test')
  await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Perfil salvo.' })).toBeVisible()
  await page.locator('#profile-avatar').setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') })
  await expect(page.getByRole('alert').filter({ hasText: 'Escolha uma imagem PNG' })).toBeVisible()
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a3ioAAAAASUVORK5CYII=', 'base64')
  await page.locator('#profile-avatar').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: png })
  await expect(page.getByRole('img', { name: 'Seu avatar', exact: true })).toBeVisible()
  await expect.poll(async () => (await rest<User>(page, '/profile')).avatar).toMatch(/^data:image\/png;base64,/)
  await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
  await expect(page.locator('#profile-currentPassword-error')).toHaveText('Informe a senha atual.')
  await page.locator('#profile-currentPassword').fill('Wrong123!')
  await page.locator('#profile-newPassword').fill('NewKurio123!')
  await page.locator('#profile-confirmPassword').fill('Mismatch123!')
  await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
  await expect(page.locator('#profile-confirmPassword-error')).toHaveText('As senhas não coincidem.')
  await page.locator('#profile-confirmPassword').fill('NewKurio123!')
  await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
  await expect(page.locator('#profile-currentPassword-error')).toHaveText('Senha incorreta.')
  await page.locator('#profile-currentPassword').fill('Kurio123!')
  await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Senha atualizada.' })).toBeVisible()
  await page.reload()
  await expect(page.locator('#profile-displayName')).toHaveValue('Colecionador E2E')
  await expect(page.getByRole('img', { name: 'Seu avatar', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remover', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Seu avatar', exact: true })).toHaveCount(0)
  await logout(page)
  await login(page, undefined, 'NewKurio123!')
  await expect(page.locator('#profile-displayName')).toHaveValue('Colecionador E2E')
})

test('wallet validation, duplicate rejection, primary selection and editing persist', async ({ page }) => {
  await login(page, undefined, undefined, '/account/wallets')
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click()
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.locator('#wallet-label-error')).toHaveText('Informe um apelido para esta carteira.')
  await expect(page.locator('#wallet-address')).toHaveAttribute('aria-invalid', 'true')
  await page.locator('#wallet-label').fill('Carteira E2E')
  await page.locator('#wallet-address').fill(`0x42${'a'.repeat(38)}`)
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.locator('#wallet-address-error')).toHaveText('Endereço já cadastrado.')
  await page.locator('#wallet-network').selectOption('Solana')
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.locator('#wallet-address-error')).toHaveText('Informe um endereço Solana válido (32 a 44 caracteres base58).')
  await page.locator('#wallet-address').fill('A'.repeat(32))
  await page.getByRole('checkbox', { name: 'Usar como carteira principal' }).check()
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  const saved = page.locator('.saved-wallet').filter({ hasText: 'Carteira E2E' })
  await expect(saved).toContainText('Principal')
  const wallets = await rest<Wallet[]>(page, '/wallets')
  expect(wallets.filter(wallet => wallet.primary)).toHaveLength(1)
  expect(wallets.find(wallet => wallet.primary)?.label).toBe('Carteira E2E')
  await saved.getByRole('button', { name: 'Editar', exact: true }).click()
  await page.locator('#wallet-label').fill('Carteira E2E editada')
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.locator('.saved-wallet').filter({ hasText: 'Carteira E2E editada' })).toBeVisible()
  await page.reload()
  await expect(page.locator('.saved-wallet').filter({ hasText: 'Carteira E2E editada' })).toBeVisible()
})

test('authentication supports keyboard submission, password visibility and desktop dialog focus', async ({ page }, testInfo) => {
  await page.goto('/login?redirect=%2Faccount')
  const email = page.locator('#auth-email')
  const password = page.locator('#auth-password')
  await email.focus()
  await page.keyboard.type('invalid')
  await page.keyboard.press('Tab')
  await expect(password).toBeFocused()
  await page.keyboard.type('Kurio123!')
  await page.getByRole('button', { name: 'Mostrar senha', exact: true }).click()
  await expect(password).toHaveAttribute('type', 'text')
  await expect(page.getByRole('button', { name: 'Ocultar senha', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await password.press('Enter')
  await expect(email).toHaveAttribute('aria-invalid', 'true')
  await expect(email).toHaveAttribute('aria-describedby', 'auth-email-error')
  if (testInfo.project.name === 'desktop-chromium') {
    const dialog = page.getByRole('dialog', { name: 'Entrar na Kurio' })
    await dialog.getByRole('button', { name: 'Fechar', exact: true }).focus()
    await page.keyboard.press('Shift+Tab')
    await expect(page.getByRole('button', { name: 'Continuar com Facebook', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Fechar', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(page).toHaveURL(/\/$/)
    await expect(page.getByRole('dialog')).toHaveCount(0)
  }
})

test('checkout validation focuses the first invalid field and associates its error', async ({ page }) => {
  await login(page)
  await seedCart(page)
  await page.goto('/checkout')
  await expect(page.getByRole('button', { name: 'Revisar compra', exact: true })).toBeEnabled()
  if (!(await page.locator('#checkout-name').isVisible())) await page.locator('.collector-form > summary').click()
  await page.locator('#checkout-name').fill('')
  await page.getByRole('button', { name: 'Revisar compra', exact: true }).click()
  await expect(page.locator('#checkout-name')).toBeFocused()
  await expect(page.locator('#checkout-name')).toHaveAttribute('aria-describedby', 'checkout-name-error')
  await expect(page.locator('#checkout-name-error')).toHaveText('Informe seu nome de exibição.')
  await page.locator('#checkout-name').fill('Colecionador Kurio')
  await page.getByRole('button', { name: 'Revisar compra', exact: true }).click()
  await expect(page.getByRole('radio').first()).toBeFocused()
  await expect(page.getByRole('alert').filter({ hasText: 'Conecte a carteira para continuar.' })).toBeVisible()
})
