test('complete catalogue to receipt purchase uses UI and keeps an immutable receipt', async ({ page }) => {
  await page.getByRole('link', { name: 'Ver Emerald Ape #042', exact: true }).click()
  await page.getByRole('button', { name: '1/10', exact: true }).click()
  const mobileBuy = page.getByRole('button', { name: 'Comprar NFT', exact: true })
  await (await mobileBuy.isVisible() ? mobileBuy : page.getByRole('button', { name: 'COMPRAR', exact: true })).click()
  await expect(page).toHaveURL(/\/cart$/)
  await expect(page.locator('.cart-row')).toContainText('Emerald Ape #042')
  await page.getByRole('link', { name: 'Conectar e finalizar', exact: true }).click()
  await expect(page).toHaveURL(/\/login\?redirect=/)
  await page.locator('#auth-email').fill('colecionador@kurio.test')
  await page.locator('#auth-password').fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/checkout$/)
  await expect(page.locator('#checkout-email')).toHaveValue('colecionador@kurio.test')
  await expect(page.getByRole('button', { name: 'Revisar compra', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await page.getByRole('button', { name: 'Revisar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revise sua compra' })).toBeVisible()
  const id = await confirm(page)
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  const snapshot = await order(page, id)
  expect(snapshot).toMatchObject({ status: 'confirmed', total: '1.206', networkFee: '0.016', userId: 'user-collector' })
  expect(snapshot.items).toMatchObject([{ nftId: 'emerald-ape-042', quantity: 1, unitPrice: '1.19', editionId: 'ten' }])
  expect((await rest<Cart>(page, '/cart')).items).toEqual([])
  await control(page, { action: 'nft-update', price: '9.99' })
  await page.reload()
  await expect(page.locator('.receipt-metadata')).toContainText('1.206 ETH')
  expect(await order(page, id)).toEqual(snapshot)
  await page.getByRole('button', { name: 'Ver transação simulada' }).click()
  await expect(page.getByRole('dialog', { name: 'Transação de demonstração' })).toBeVisible()
  await page.getByRole('button', { name: 'Entendi', exact: true }).click()
  await logout(page)
  await login(page, 'nova@kurio.test', undefined, `/order/${id}`)
  await expect(page.getByRole('alert')).toContainText('Pedido não encontrado.')
  await expect(page.locator('.order-receipt')).toHaveCount(0)
})

test('declined payment preserves the cart and allows a reviewed new attempt', async ({ page }) => {
  await login(page)
  await seedCart(page)
  await checkout(page)
  await control(page, { action: 'scenario', scenario: 'payment-declined' })
  const declinedId = await confirm(page)
  await expect(page.getByRole('heading', { name: 'Seu pagamento foi recusado' })).toBeVisible()
  expect((await rest<Cart>(page, '/cart')).items).toHaveLength(1)
  expect((await order(page, declinedId)).status).toBe('declined')
  await control(page, { action: 'scenario', scenario: 'success' })
  await page.getByRole('link', { name: 'Revisar e tentar novamente' }).click()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await page.getByRole('button', { name: 'Revisar compra', exact: true }).click()
  const confirmedId = await confirm(page)
  expect(confirmedId).not.toBe(declinedId)
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  expect((await order(page, declinedId)).status).toBe('declined')
})

test('repeated confirmation sends one idempotent order and decrements stock once', async ({ page }) => {
  await login(page)
  await seedCart(page, 2)
  await checkout(page)
  const posts: PlaceOrderInput[] = []
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders') posts.push(request.postDataJSON() as PlaceOrderInput) })
  const button = page.getByRole('button', { name: 'Confirmar compra', exact: true })
  await button.focus()
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/\/order\/[^/?]+$/)
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  expect(posts).toHaveLength(1)
  const receipt = await order(page, page.url().split('/').at(-1)!)
  const recovered = await rest<Order>(page, `/orders/by-key/${posts[0].idempotencyKey}`)
  expect(recovered.id).toBe(receipt.id)
  const asset = await rest<{ editions: { id: string; stock: number }[] }>(page, '/nfts/emerald-ape-042')
  expect(asset.editions.find(edition => edition.id === 'ten')?.stock).toBe(8)
})

test('timeout after order creation and refresh recover the exact same order key', async ({ page }) => {
  await login(page)
  await seedCart(page)
  await checkout(page)
  await control(page, { action: 'scenario', scenario: 'order-timeout' })
  const submittedKeys: string[] = []
  page.on('request', request => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders') submittedKeys.push((request.postDataJSON() as PlaceOrderInput).idempotencyKey) })
  const post = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders')
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  const input = (await post).postDataJSON() as PlaceOrderInput
  await expect.poll(async () => {
    const result = await page.evaluate(async (key) => {
      const response = await fetch(`/api/orders/by-key/${key}`, { headers: { Authorization: `Bearer ${localStorage.getItem('kurio.session')}`, 'X-Visitor-Id': localStorage.getItem('kurio.visitor') ?? '' } })
      return response.status
    }, input.idempotencyKey)
    return result
  }).toBe(200)
  const created = await rest<Order>(page, `/orders/by-key/${input.idempotencyKey}`)
  // Axios must actually time out; the browser then recovers via REST without reposting.
  await expect(page).toHaveURL(new RegExp(`/order/${created.id}$`), { timeout: 15000 })
  await expect(page.getByRole('heading', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  await page.goto('/checkout')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
  expect((await rest<Order>(page, `/orders/by-key/${input.idempotencyKey}`)).id).toBe(created.id)
  expect((await order(page, created.id)).items).toMatchObject([{ quantity: 1 }])
  expect(submittedKeys).toEqual([input.idempotencyKey])
})
